import * as path from "node:path";
import type { TimerHost } from "./host";
import type { TickerUnitInput } from "./plan";

export const TICKER_LAUNCHD_LABEL = "sh.omp.timer-tick";

export function launchdPlistPath(host: TimerHost): string {
	return path.join(host.home, "Library", "LaunchAgents", `${TICKER_LAUNCHD_LABEL}.plist`);
}

export function launchdTarget(host: TimerHost): string {
	return `gui/${host.uid}/${TICKER_LAUNCHD_LABEL}`;
}

function xmlEscape(value: string): string {
	return value
		.replace(/&/g, "&amp;")
		.replace(/</g, "&lt;")
		.replace(/>/g, "&gt;")
		.replace(/"/g, "&quot;")
		.replace(/'/g, "&apos;");
}

function xmlUnescape(value: string): string {
	return value.replace(/&(amp|lt|gt|quot|apos|#\d+|#x[0-9a-fA-F]+);/g, (_, entity: string) => {
		switch (entity) {
			case "amp":
				return "&";
			case "lt":
				return "<";
			case "gt":
				return ">";
			case "quot":
				return '"';
			case "apos":
				return "'";
		}
		const code = entity.startsWith("#x")
			? Number.parseInt(entity.slice(2), 16)
			: Number.parseInt(entity.slice(1), 10);
		return String.fromCodePoint(code);
	});
}

export function renderTickerPlist(input: TickerUnitInput): string {
	const str = (value: string) => `<string>${xmlEscape(value)}</string>`;
	const argv = [...input.ompCommand, "timer", "tick"];
	const env = Object.entries(input.env)
		.map(([key, value]) => `\t\t<key>${xmlEscape(key)}</key>\n\t\t${str(value)}`)
		.join("\n");
	return [
		'<?xml version="1.0" encoding="UTF-8"?>',
		'<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">',
		"<!-- Generated by `omp timer install`; re-run it instead of editing this file. -->",
		'<plist version="1.0">',
		"<dict>",
		"\t<key>Label</key>",
		`\t${str(TICKER_LAUNCHD_LABEL)}`,
		"\t<key>ProgramArguments</key>",
		"\t<array>",
		...argv.map(arg => `\t\t${str(arg)}`),
		"\t</array>",
		"\t<key>StartCalendarInterval</key>",
		"\t<dict/>",
		"\t<key>RunAtLoad</key>",
		"\t<true/>",
		"\t<key>AbandonProcessGroup</key>",
		"\t<true/>",
		"\t<key>ProcessType</key>",
		`\t${str("Standard")}`,
		"\t<key>EnvironmentVariables</key>",
		env ? `\t<dict>\n${env}\n\t</dict>` : "\t<dict/>",
		"\t<key>StandardOutPath</key>",
		`\t${str(input.logPath)}`,
		"\t<key>StandardErrorPath</key>",
		`\t${str(input.logPath)}`,
		"</dict>",
		"</plist>",
		"",
	].join("\n");
}

export type PlistValue = string | number | boolean | PlistValue[] | { [key: string]: PlistValue };

/** Parses the XML plist subset launchd agents use (dict, array, string, integer, real, true, false). */
export function parsePlist(xml: string): PlistValue {
	const tokens = [...xml.replace(/<!--[\s\S]*?-->/g, "").matchAll(/<(\/?)([A-Za-z]+)[^>]*?(\/?)>|([^<]+)/g)];
	let index = 0;
	const next = () => tokens[index++];
	const skipToTag = () => {
		while (index < tokens.length && tokens[index][2] === undefined) index++;
	};
	const readText = (tag: string): string => {
		let text = "";
		while (index < tokens.length) {
			const token = next();
			if (token[2] === undefined) {
				text += token[4];
				continue;
			}
			if (token[1] === "/" && token[2] === tag) return xmlUnescape(text);
			throw new Error(`plist: unexpected <${token[2]}> inside <${tag}>`);
		}
		throw new Error(`plist: unterminated <${tag}>`);
	};
	const readValue = (): PlistValue => {
		skipToTag();
		const token = next();
		if (!token || token[1] === "/") throw new Error("plist: expected a value");
		const [, , tag, selfClosing] = token;
		switch (tag) {
			case "true":
				return true;
			case "false":
				return false;
			case "string":
				return selfClosing ? "" : readText("string");
			case "integer":
			case "real":
				return Number(readText(tag));
			case "array": {
				const items: PlistValue[] = [];
				if (selfClosing) return items;
				for (;;) {
					skipToTag();
					if (tokens[index]?.[1] === "/" && tokens[index][2] === "array") {
						index++;
						return items;
					}
					items.push(readValue());
				}
			}
			case "dict": {
				const dict: { [key: string]: PlistValue } = {};
				if (selfClosing) return dict;
				for (;;) {
					skipToTag();
					const keyToken = next();
					if (!keyToken) throw new Error("plist: unterminated <dict>");
					if (keyToken[1] === "/" && keyToken[2] === "dict") return dict;
					if (keyToken[2] !== "key") throw new Error(`plist: expected <key>, got <${keyToken[2]}>`);
					const key = readText("key");
					dict[key] = readValue();
				}
			}
			default:
				throw new Error(`plist: unsupported <${tag}>`);
		}
	};
	for (;;) {
		skipToTag();
		const token = next();
		if (!token) throw new Error("plist: missing <plist> root");
		if (token[2] === "plist" && token[1] !== "/") return readValue();
	}
}

/** Command + env baked into an installed ticker plist; `undefined` when unparseable. */
export function readTickerPlist(xml: string): { argv: string[]; env: Record<string, string> } | undefined {
	let root: PlistValue;
	try {
		root = parsePlist(xml);
	} catch {
		return undefined;
	}
	if (typeof root !== "object" || Array.isArray(root)) return undefined;
	const args = root.ProgramArguments;
	if (!Array.isArray(args)) return undefined;
	const env: Record<string, string> = {};
	const vars = root.EnvironmentVariables;
	if (vars && typeof vars === "object" && !Array.isArray(vars)) {
		for (const [key, value] of Object.entries(vars)) if (typeof value === "string") env[key] = value;
	}
	return { argv: args.filter((arg): arg is string => typeof arg === "string"), env };
}
