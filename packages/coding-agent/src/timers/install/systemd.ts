import * as path from "node:path";
import type { TimerHost } from "./host";
import type { TickerUnitInput } from "./plan";

export const TICKER_SYSTEMD_UNIT = "omp-timer-tick";

export function systemdUnitDir(host: TimerHost): string {
	return path.join(host.home, ".config", "systemd", "user");
}

export function systemdServicePath(host: TimerHost): string {
	return path.join(systemdUnitDir(host), `${TICKER_SYSTEMD_UNIT}.service`);
}

export function systemdTimerPath(host: TimerHost): string {
	return path.join(systemdUnitDir(host), `${TICKER_SYSTEMD_UNIT}.timer`);
}

/**
 * Quotes one word for a systemd unit setting: double quotes with C escapes, `%` specifiers
 * doubled, and (for `ExecStart=`, which expands `$VAR`) `$` doubled.
 */
function quoteSystemdWord(value: string, escapeDollar: boolean): string {
	let out = value
		.replace(/\\/g, "\\\\")
		.replace(/"/g, '\\"')
		.replace(/\n/g, "\\n")
		.replace(/\t/g, "\\t")
		.replace(/%/g, "%%");
	if (escapeDollar) out = out.replace(/\$/g, "$$$$");
	return `"${out}"`;
}

export function renderTickerService(input: TickerUnitInput): string {
	const argv = [...input.ompCommand, "timer", "tick"];
	const logTarget = `append:${input.logPath.replace(/%/g, "%%")}`;
	return [
		"# Generated by `omp timer install`; re-run it instead of editing this file.",
		"[Unit]",
		"Description=omp timer tick (fires due omp timers)",
		"",
		"[Service]",
		"Type=oneshot",
		`ExecStart=${argv.map(arg => quoteSystemdWord(arg, true)).join(" ")}`,
		...Object.entries(input.env).map(([key, value]) => `Environment=${quoteSystemdWord(`${key}=${value}`, false)}`),
		"KillMode=process",
		`StandardOutput=${logTarget}`,
		`StandardError=${logTarget}`,
		"",
	].join("\n");
}

export function renderTickerTimer(): string {
	return [
		"# Generated by `omp timer install`; re-run it instead of editing this file.",
		"[Unit]",
		"Description=omp timer tick, every minute",
		"",
		"[Timer]",
		"OnCalendar=minutely",
		"Persistent=true",
		"AccuracySec=1s",
		`Unit=${TICKER_SYSTEMD_UNIT}.service`,
		"",
		"[Install]",
		"WantedBy=timers.target",
		"",
	].join("\n");
}

const C_ESCAPES: Record<string, string> = { n: "\n", t: "\t", r: "\r", "\\": "\\", '"': '"', "'": "'" };

/** Splits a systemd setting value into words, undoing the quoting `renderTickerService` applies. */
export function splitSystemdWords(value: string, unescapeDollar: boolean): string[] {
	const words: string[] = [];
	let i = 0;
	while (i < value.length) {
		while (i < value.length && /\s/.test(value[i])) i++;
		if (i >= value.length) break;
		let word = "";
		const quote = value[i] === '"' || value[i] === "'" ? value[i++] : undefined;
		while (i < value.length) {
			const ch = value[i];
			if (quote ? ch === quote : /\s/.test(ch)) {
				if (quote) i++;
				break;
			}
			if (ch === "\\" && i + 1 < value.length) {
				word += C_ESCAPES[value[i + 1]] ?? value[i + 1];
				i += 2;
				continue;
			}
			if (ch === "%" && value[i + 1] === "%") {
				word += "%";
				i += 2;
				continue;
			}
			if (unescapeDollar && ch === "$" && value[i + 1] === "$") {
				word += "$";
				i += 2;
				continue;
			}
			word += ch;
			i++;
		}
		words.push(word);
	}
	return words;
}

/** Command + env baked into an installed ticker service unit; `undefined` without an `ExecStart=`. */
export function readTickerService(unit: string): { argv: string[]; env: Record<string, string> } | undefined {
	let argv: string[] | undefined;
	const env: Record<string, string> = {};
	for (const line of unit.split("\n")) {
		const match = /^\s*(ExecStart|Environment)\s*=\s*(.*)$/.exec(line);
		if (!match) continue;
		if (match[1] === "ExecStart") {
			argv = splitSystemdWords(match[2], true);
			continue;
		}
		for (const assignment of splitSystemdWords(match[2], false)) {
			const eq = assignment.indexOf("=");
			if (eq > 0) env[assignment.slice(0, eq)] = assignment.slice(eq + 1);
		}
	}
	return argv ? { argv, env } : undefined;
}
